/**
 * Demo / fallback listings.
 *
 * These are the cars the site shows when Strapi has nothing to serve. They are
 * NOT real listings and no real seller is attached to any of them — `authorName`
 * and `authorImage` are null on every entry, exactly as `lib/strapi.js#toCar()`
 * leaves them, because inventing a seller on a marketplace whose whole promise
 * is verified listings is the one thing we must never do.
 *
 * Everything else is anchored to the real Omani market in the NICHE.md band:
 *
 * - Every price is OMR 1,500–6,000, except three cars priced 1,000–1,499 which
 *   carry `soldAsIs: true` so the as-is disclosure path is exercised.
 *   Prices/years/mileage are set together — a 2019 Sunny is not a 2008 Prado.
 * - Mileage is in km and brutal, which is normal in this band (140k–380k).
 * - Cities are real Omani ones; there are no US/EU place names.
 * - `importOrigin` is a realistic mix (mostly GCC, a real share of US imports,
 *   a couple of Japan imports, and two where the seller has not stated it —
 *   `importOriginLabel()` surfaces that gap rather than hiding it).
 * - Photos are the AI-generated stand-ins in `/assets/images/listings` where a
 *   model matches; see that folder's README. Cars with no matching stand-in
 *   keep the theme's blank grey placeholder, which is honest: no photo yet.
 */

